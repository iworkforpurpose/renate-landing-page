export function getJobBySlug(slug) {
  return JOBS.find((j) => j.slug === slug)
}

export function getCandidate(jobSlug, candidateSlug) {
  const job = getJobBySlug(jobSlug)
  if (!job) return null
  return job.candidates.find((c) => c.slug === candidateSlug)
}

